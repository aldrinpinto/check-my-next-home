// ----------------------------------------------------------------
// The delivery record — the shelf's shape, held here
// (the lib/gift.ts pattern: the record type is pure,
// the store behind its server seam fills it).

export type DeliveryKind = "free" | "paid" | "gifted";

export interface DeliveryRecord {
  // The link's payload: 24 random bytes as 32 base64url
  // characters, generated by the store — un-guessable,
  // never derived from anything about the order, the
  // buyer or the home.
  id: string;
  // Stored normalised (trimmed, lower-cased — the
  // lib/gift.ts comparison rule); every write path
  // normalises on the way in, and the re-issue decision
  // compares against this stored form.
  email: string;
  kind: DeliveryKind;
  // The stored PDF's key (lib/report-pdf.ts's
  // reportPdfKey) — a re-send serves the stored file
  // through lib/server/report-storage.ts, never a
  // regeneration.
  pdfKey: string;
  // The downloaded file's name (lib/report-pdf.ts's
  // reportPdfFileName), carried so the file route names
  // the download exactly as generation named it.
  fileName: string;
  // The home's identity in the forms the emails carry:
  // the title for the subjects ("12 Willow Close"; a
  // whole-postcode report's title is its postcode) and
  // the full address line for the bodies ("12 Willow
  // Close, Millbrook MB3 4QX").
  homeTitle: string;
  homeAddressLine: string;
  // The Check Together gift this delivery issued —
  // PAID deliveries only (D21: exactly one per paid
  // order; free and gifted deliveries carry none). The
  // token itself, so the delivery email's gift block
  // links the claim page; null otherwise.
  giftToken: string | null;
  // M9's order record id, carried so a delivery can be
  // traced to its order. Null until M9 wires delivery.
  orderRef: string | null;
  createdAt: Date;
}

// ----------------------------------------------------------------
// The token form
//
// A download token is three dot-joined parts: the
// delivery id, the expiry instant (milliseconds since
// the epoch, decimal) and the signature over the first
// two (lib/server/download-links.ts). The expiry rides
// INSIDE the signed payload, so verification is
// stateless and a re-issue mints a wholly new token
// without touching the old one — the old link keeps
// its own seventh day. This is the form a route
// accepts before it spends a verification or a
// database read.

export const DOWNLOAD_TOKEN_FORM = /^[A-Za-z0-9_-]{24,64}\.\d{10,16}\.[A-Za-z0-9_-]{32,64}$/;

export function isDownloadTokenForm(candidate: string): boolean {
  return DOWNLOAD_TOKEN_FORM.test(candidate);
}

// ----------------------------------------------------------------
// Routes — the flow's own shapes. The emailed link is
// the landing path itself: one URL serves the PDF
// while the link lives, the expired page once it dies,
// and the error page (via the landing page's
// not-recognised state) when it was never genuine.

export function downloadPath(token: string): string {
  return `/report/download/${token}`;
}

export function downloadFilePath(token: string): string {
  return `/report/download/${token}/file`;
}

export function downloadReissuePostPath(token: string): string {
  return `/report/download/${token}/reissue`;
}

// The download's Content-Disposition: the descriptive
// file name rides in its UTF-8 form (RFC 5987
// filename*), with a plain-ASCII fallback — the
// lib/report-pdf.ts sample twin's exact discipline.
export function downloadContentDisposition(fileName: string): string {
  const fallback = fileName.replace(/—/g, "-");
  return `attachment; filename="${fallback}"; filename*=UTF-8''${encodeURIComponent(fileName)}`;
}

// ----------------------------------------------------------------
// The landing page's served states
//
// Verification is the signer's three-state answer
// (lib/server/download-links.ts): the signature is
// genuine and the link in date ("ok"), genuine but
// past its seventh day ("expired"), or not genuine at
// all ("invalid" — made-up, mistyped or tampered, all
// one answer). The page serves by that state, always:
// the file while the link lives, the expired card once
// it dies (or the sent card over the same form, after
// a re-issue request), and the site's error page for
// anything not genuine. The signer's type is mirrored
// here so this module stays free of the server seam.

export type DownloadVerification =
  | { kind: "ok"; deliveryId: string; expiresAt: Date }
  | { kind: "expired"; deliveryId: string; expiresAt: Date }
  | { kind: "invalid" };

export type DownloadLandingView =
  { kind: "serve" } | { kind: "expired" } | { kind: "sent" } | { kind: "not-recognised" };

export function downloadLandingView(
  verification: DownloadVerification,
  flags: { sent?: boolean },
): DownloadLandingView {
  if (verification.kind === "invalid") return { kind: "not-recognised" };
  if (verification.kind === "ok") return { kind: "serve" };
  // Expired: the sent presentation stands over the same
  // form once a re-issue has been asked for (?sent=1 —
  // the journey's query-flag pattern); the flag selects
  // a presentation of the state the link is already in
  // and can never create one.
  return flags.sent ? { kind: "sent" } : { kind: "expired" };
}

// ----------------------------------------------------------------
// The re-issue decision
//
// One function decides every re-issue request, so the
// route handler only executes. A fresh link is sent
// only when the entered address IS the delivery's own
// address — the fresh link goes to the original inbox
// only — and every other case (no such delivery, a
// different address, a malformed address) is the same
// "no-send". The route answers identically either way;
// this decision is visible only in whether an email
// leaves the building.

export function decideReissue(
  delivery: DeliveryRecord | null,
  normalisedEmail: string,
): "send" | "no-send" {
  if (!delivery) return "no-send";
  return normalisedEmail === delivery.email ? "send" : "no-send";
}

