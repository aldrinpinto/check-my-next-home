// brand-new key generated by the account's own Reset on
// 13 Nov 2026. DWP's error text ends "Please contact your
// system administrator" — the account's API entitlement is
// DWP's to restore. Until it is, every live call from this
// loader fails with that 401 and nothing UC files; the
// loader, its filing path, its tests and its canary probe
// are all built and green against the documented API shape
// and the fixture. The single remaining step, named here
// and in the connector doc, is PENDING_FIRST_PULL (below):
// the first keyed verify-only pull, which locks the UC
// golden values and reconciles the schema discovery and
