-- Migration 0034 — Check Together gift tokens (plan
-- step M7.13, decision D21; the claim shell).
--
-- One row per gift. A gift is created ONLY on a paid
-- order — that creation is M9.6's, at the payment/order
-- record, exactly one per paid order, never on a
-- free-window or gifted order — and this table is the
-- stored gift linkage the claim page enforces the
-- different-email rule and single use against. The
-- shell built at M7.13 exercises every transition
-- against this table through the store seam
-- (lib/server/gifts.ts); M9.6 wires issuance and the
-- redemption call, M9.8 the refund void.
--
-- The lifecycle (D21 as amended): Issued → Claimed
-- (bound to the claimant's email, NOT consumed) →
-- Redeemed (consumed only when a report is delivered
-- to that email) → Expired (30 days after purchase).
-- The status column holds the three stored states;
-- Expired is DERIVED at read time from expires_at, so
-- no job has to flip rows at midnight on day 30, and a
-- redeemed row is never reclassified (redemption is
-- final — it keeps its "already used" answer after the
-- 30 days too).
--
-- Binding happens only through the email-confirmation
-- round-trip (adopted gap check item 1): a claim
-- attempt writes pending_email + pending_token and
-- sends the confirmation email; clicking its link is
-- what binds. A typo therefore binds nothing — the
-- pending is replaced wholesale by the next attempt,
-- so only the latest link can ever bind.
--
-- Emails are stored NORMALISED (trimmed, lower-cased —
-- the comparison rule, fold-in G9); every write path
-- normalises on the way in. The token is the
-- credential: 24 random bytes as 32 base64url
-- characters, generated by the store, never derived
-- from anything about the order or the buyer.
--
-- order_ref carries M9.6's order record id so the gift
-- can be traced to (and voided with) its order at
-- M9.8. It is null until M9.6 wires issuance.

CREATE TABLE gift_tokens (
  token text PRIMARY KEY,
  buyer_email text NOT NULL,
  claimant_email text,
  status text NOT NULL DEFAULT 'issued'
    CHECK (status IN ('issued', 'claimed', 'redeemed')),
  order_ref text,
  issued_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  claimed_at timestamptz,
  redeemed_at timestamptz,
  pending_email text,
  pending_token text,
  pending_sent_at timestamptz
);

-- The auto-apply lookup (M9.6): the claimed gift bound
-- to an email, if one is live.
CREATE INDEX gift_tokens_claimant_idx
  ON gift_tokens (claimant_email)
  WHERE claimant_email IS NOT NULL;

-- The confirmation link resolves by its own credential.
CREATE UNIQUE INDEX gift_tokens_pending_token_idx
  ON gift_tokens (pending_token)
  WHERE pending_token IS NOT NULL;
